//! Build script: the app's own commands, each one an allow-list entry the page must be granted
//! in a capability file. The test bridge's command and its capability exist only in a testhook
//! build; a normal build's capabilities folder is the only one it reads.

/// Every command the page may call (web/src/platform/shell.ts), in snake_case.
/// Keep this list and the handlers in lib.rs in step.
const COMMANDS: &[&str] = &[
    "shell_info",
    "file_pick_open",
    "file_pick_save",
    "file_stat",
    "file_read",
    "file_write_begin",
    "write_chunk",
    "write_end",
    "file_reveal",
    "pending_take",
    "recent_list",
    "recent_add",
    "recent_remove",
    "recent_clear",
    "kept_list",
    "kept_read",
    "kept_write_begin",
    "kept_remove",
    "window_state",
    "window_close",
    "open_external",
];

/// Commands only a testhook build has.
const TEST_COMMANDS: &[&str] = &["test_result"];

fn main() {
    let testhook = std::env::var_os("CARGO_FEATURE_TESTHOOK").is_some();
    let mut commands: Vec<&str> = COMMANDS.to_vec();
    // Only a testhook build reads capabilities-test/ (the test bridge's capability).
    let pattern: &'static str = if testhook {
        commands.extend_from_slice(TEST_COMMANDS);
        "./capabilities*/**/*"
    } else {
        "./capabilities/**/*"
    };
    // tauri-build writes one permission file per command but never removes the ones of commands
    // that are gone: a normal build must not keep the test bridge's permission from a testhook build.
    if let Ok(entries) = std::fs::read_dir("permissions/autogenerated") {
        for entry in entries.flatten() {
            let file = entry.file_name().to_string_lossy().into_owned();
            let stem = file.strip_suffix(".toml").unwrap_or("");
            if !commands.iter().any(|c| *c == stem) {
                let _ = std::fs::remove_file(entry.path());
            }
        }
    }
    let commands: &'static [&'static str] = Box::leak(commands.into_boxed_slice());

    let attributes = tauri_build::Attributes::new()
        .capabilities_path_pattern(pattern)
        .app_manifest(tauri_build::AppManifest::new().commands(commands));
    tauri_build::try_build(attributes).expect("failed to run tauri-build");
}
