const fieldMap = (fields: readonly FieldDefault[]): Map<string, FieldDefault> => new Map(fields.map((f) => [f.name, f]));
export const DOOR_FIELD_MAP = fieldMap(DOOR_FIELDS);
export const WINDOW_FIELD_MAP = fieldMap(WINDOW_FIELDS);

/** what the record says for a field: a number, a boolean or text; unknown and mistyped values fall back to the default given */
type Get = (field: string) => unknown;
const num = (get: Get, field: string, fallback: number): number => {
  const v = get(field);
  return typeof v === "number" && Number.isFinite(v) ? v : fallback;
};
const flag = (get: Get, field: string): boolean => get(field) === true;
const text = (get: Get, field: string, fallback: string): string => {
  const v = get(field);
  return typeof v === "string" && v !== "" ? v : fallback;
};

const DOOR_CONFIG_NAMES: readonly string[] = [
  "Swing Simple", "Swing Bi-part", "Swing Double Acting", "Swing Dutch", "Pocket Simple", "Pocket Bi-part", "Slider",
  "Bi-fold Simple", "Bi-fold Bi-part", "Barn Bypass", "Barn Simple", "Overhead", "Revolving", "Opening", "Cased Opening",
];
const WINDOW_CONFIG_NAMES: readonly string[] = [
  "Fixed Glass", "Casement", "Awning", "Hopper", "Double Hung", "Single Hung", "Sliding (H)", "Pivot", "Louver", "Opening",
];

/** the door's parameters from its record's fields (DoorWidth, Config, LeafType, OpenAngle, ...); wallThickness comes from the wall it is in */
export function doorParams(get: Get, wallThickness: number): DoorParams {
  const configName = text(get, "Config", "Swing Simple");
  const leafName = text(get, "LeafType", "Solid");
  const leaf: LeafKind = leafName === "Panel" || leafName === "Glass" ? leafName : "Solid";
  // a transom's height has no field in the 2023 layout; TopPanelHeight is the nearest and is unverified
  const transom = flag(get, "Transom") ? num(get, "TopPanelHeight", 0) : 0;
  return {
    width: num(get, "DoorWidth", 900),
    height: num(get, "DoorHeight", 2100),
    config: (DOOR_CONFIG_NAMES.includes(configName) ? configName : "Swing Simple") as DoorConfig,
    thickness: num(get, "DoorThickness", 40),
    jambWidth: num(get, "JambWidth", 50),
    jambDepth: num(get, "JambDepth", 100),
    wallThickness,
    openAngle: num(get, "OpenAngle", 90),
    leaf,
    threshold: flag(get, "Threshold"),
    transom,
    sideLights: {
      left: flag(get, "SideLights") ? num(get, "LeftLiteWidth", 0) : 0,
      right: flag(get, "SideLights") ? num(get, "RightLiteWidth", 0) : 0,
    },
    trim: {
      interior: flag(get, "IntTrim") ? num(get, "IntTrimWidth", 0) : 0,
      exterior: flag(get, "ExtTrim") ? num(get, "ExtTrimWidth", 0) : 0,
    },
  };
}

/** the window's parameters from its record's fields; the sill is the Elevation, measured to the head or the sill as ElevationSetAt says */
export function windowParams(get: Get, wallThickness: number): WindowParams {
  const height = num(get, "Height", 1200);
  const elevation = num(get, "Elevation", 2100);
  const atHead = text(get, "ElevationSetAt", "Sill of Window").includes("Head");
  // a custom sash operation names its operation in CustSashOpPopup
  const operation = text(get, "SashOperation", "Fixed Glass");
  const configName = operation === "Custom" ? text(get, "CustSashOpPopup", "Fixed Glass") : operation;
  return {
    width: num(get, "Width", 1200),
    height,
    sill: atHead ? elevation - height : elevation,
    config: (WINDOW_CONFIG_NAMES.includes(configName) ? configName : "Fixed Glass") as WindowConfig,
    jambWidth: num(get, "JambWidth", 50),
    jambDepth: num(get, "JambDepth", 100),
    sashWidth: num(get, "SashWidth", 19.05),
    sashDepth: num(get, "SashDepth", 38.1),
    wallThickness,
    columns: Math.max(1, Math.round(num(get, "Cols", 1))),
    rows: Math.max(1, Math.round(num(get, "Rows", 1))),
    sillDepth: flag(get, "IncludeSill") ? num(get, "SillDepth", 0) : 0,
    trim: {
      interior: flag(get, "IntTrim") ? num(get, "IntTrimWidth", 0) : 0,
      exterior: flag(get, "ExtTrim") ? num(get, "ExtTrimWidth", 0) : 0,
    },
  };
}
