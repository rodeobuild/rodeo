/** The Space format's fields, in order, as Vectorworks of `year` writes them (2023 the earliest known, 2025 on the latest). */
export function spaceFields(year: number): PluginFieldSpec[] {
  const old = year <= 2023;
  return ROWS.filter((r) => (r[3] ?? 0) <= year).map(([name, type, value, , was]) => ({ name, type: old && was ? was : type, value }));
}
