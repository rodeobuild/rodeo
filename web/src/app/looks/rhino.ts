/** A toolbar or sidebar button that picks one of Rodeo's tools. */
const tool = (label: string, id: ToolId, keys?: string): LookButton => ({ label, do: { tool: id }, keys });

/** A button that runs one of Rodeo's menu commands by its path. */
const menu = (label: string, path: string, keys?: string): LookButton => ({ label, do: { menu: path }, keys });

/** A button that shows one of Rodeo's palettes. */
const palette = (label: string, id: string, keys?: string): LookButton => ({ label, do: { palette: id }, keys });

/** Rhino's osnap modes all share Rodeo's one object snap, which the menu row turns on and off. */
const SNAP: Command = { menu: "View › Snap to Objects" };

/** A row of Rhino's object snap toggles: each is a check mark that lights while object snapping is on. */
const osnap = (label: string): StatusItem => ({ kind: "toggle", label, do: SNAP, style: "check" });

